# ---------------------------------------------------------------- scene helpers
SCENES = {}

def track(n, keys, default):
    out, v = [], default
    for i in range(n + 1):
        if i in keys:
            v = keys[i]
        out.append(v)
    return out

def scene(name, n, els, waits=None):
    """els: {id: {"p": {step:(x,y)}, "o": {step:op}, "c": {step:cls}, "t": {step:text}}}"""
    spec = {"n": n, "w": [(waits or {}).get(i, 1100) for i in range(n + 1)], "e": {}}
    for eid, tr in els.items():
        e = {}
        if "p" in tr: e["p"] = track(n, tr["p"], (0, 0))
        if "o" in tr: e["o"] = track(n, tr["o"], 1)
        if "c" in tr: e["c"] = track(n, tr["c"], "")
        if "t" in tr: e["t"] = track(n, tr["t"], "")
        spec["e"][eid] = e
    SCENES[name] = spec
    return f'data-scene="{name}"'

def svg(vb, body, cls="dg"):
    return f'<svg class="{cls}" viewBox="{vb}" role="img">{body}</svg>'

# ---------------------------------------------------------------- svg primitives
def sbox(eid, x, y, w, h, label, sub="", cls="", fs=21, rx=12):
    """Прямоугольник с подписью. data-id на rect — сцена меняет его класс."""
    cx, cy = x + w / 2, y + h / 2
    s = f'<rect data-id="{eid}" x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" class="sbx {cls}"/>' if eid \
        else f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" class="sbx {cls}"/>'
    dy = -7 if sub else 7
    s += f'<text class="bxt" x="{cx}" y="{cy + dy}" text-anchor="middle" font-size="{fs}">{label}</text>'
    if sub:
        s += f'<text class="stx" x="{cx}" y="{cy + 20}" text-anchor="middle">{sub}</text>'
    return s

def harr(x1, x2, y, cls="lnk"):
    return (f'<line class="{cls}" x1="{x1}" y1="{y}" x2="{x2 - 14}" y2="{y}"/>'
            f'<polygon points="{x2},{y} {x2 - 16},{y - 8} {x2 - 16},{y + 8}" class="arh"/>')

def varr(y1, y2, x, cls="lnk"):
    d = 1 if y2 > y1 else -1
    return (f'<line class="{cls}" x1="{x}" y1="{y1}" x2="{x}" y2="{y2 - 14 * d}"/>'
            f'<polygon points="{x},{y2} {x - 8},{y2 - 16 * d} {x + 8},{y2 - 16 * d}" class="arh"/>')

def cap(eid, x, y, anchor="middle", cls="capm"):
    return f'<text data-id="{eid}" class="{cls}" x="{x}" y="{y}" text-anchor="{anchor}"></text>'

def chip(eid, x, y, w, h, text, cls="pk-m", fs=19):
    return (f'<g data-id="{eid}" class="an">'
            f'<rect x="{-w / 2}" y="{-h / 2}" width="{w}" height="{h}" rx="8" class="{cls}" transform="translate({x} {y})"/>'
            f'<text class="pkt" x="{x}" y="{y + 6}" text-anchor="middle" font-size="{fs}">{text}</text></g>')

# ---------------------------------------------------------------- markup helpers
def steps(items, start=1, cls=""):
    return f'<ol class="steps {cls}">' + "".join(
        f'<li data-s="{start + i}"><span class="badge">{i + 1}</span><div>{t}</div></li>'
        for i, t in enumerate(items)) + '</ol>'

def fcards(items, start=1, cols="g2"):
    return f'<div class="{cols}">' + "".join(
        f'<article class="card fc {c}" data-s="{start + i}"><div class="ftag mono">{n}</div><p>{t}</p></article>'
        for i, (n, c, t) in enumerate(items)) + '</div>'

def scbox(svgcode, sc, cls=""):
    return f'<div class="card dgcard {cls}" {sc}>{svgcode}</div>'

def table(rows, head, cls="", mono=0):
    """mono — индекс столбца, который печатается моноширинным."""
    r = ""
    for i, row in enumerate(rows):
        cells = "".join(
            f'<th>{c}</th>' if k == 0 else f'<td class="{"mono" if k == mono else ""}">{c}</td>'
            for k, c in enumerate(row))
        r += f'<tr data-s="{i + 1}">{cells}</tr>'
    h = "".join(f'<th>{c}</th>' for c in head)
    return f'<div class="tw card"><table class="tbl {cls}"><thead><tr>{h}</tr></thead><tbody>{r}</tbody></table></div>'

def term(lines, cls="", title=""):
    """lines: ('$', 'команда') | ('#', 'команда') | ('', 'вывод') | ('~', 'комментарий')"""
    body = ""
    if title:
        body += f'<div class="dimt tcap">{title}</div>'
    for kind, txt in lines:
        if kind in ("$", "#"):
            body += f'<div><span class="pr">{kind}</span> <span class="cm">{txt}</span></div>'
        elif kind == "~":
            body += f'<div class="cmt"># {txt}</div>'
        else:
            body += f'<div class="ot">{txt}</div>'
    return f'<div class="card term mono {cls}">{body}</div>'

def cmds(items, cols="g2"):
    """Плитки «команда — описание»."""
    return f'<div class="{cols} cmdg">' + "".join(
        f'<article class="card cmdc" data-s="{i + 1}"><div class="mono cmdn">{n}</div><p>{t}</p></article>'
        for i, (n, t) in enumerate(items)) + '</div>'

def qa(items):
    return '<div class="qas">' + "".join(
        f'<article class="card qa" data-s="{i + 1}"><div class="qq"><span class="badge">{i + 1}</span><b>{q}</b></div>'
        f'<button class="btn qa-b" type="button">Показать ответ</button><p class="qa-a" hidden>{a}</p></article>'
        for i, (q, a) in enumerate(items)) + '</div>'

def tree(lines):
    """Белая панель с деревом каталогов: (отступ, текст, подпись)"""
    body = ""
    for lvl, txt, note in lines:
        n = f'<span class="wnote">{note}</span>' if note else ""
        body += f'<div class="wl i{lvl}">{txt}{n}</div>'
    return f'<div class="wsk"><div class="wsd">{body}</div></div>'

def callout(text, cls=""):
    return f'<div class="callout {cls}">{text}</div>'

